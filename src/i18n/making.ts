export type MakingKey = keyof typeof text;

type LocaleIndex = 0 | 1 | 2 | 3 | 4 | 5 | 6 | 7;
const localeIndex: Record<Locale, LocaleIndex> = {en: 0, zh: 1, fr: 2, de: 3, es: 4, ko: 5, ja: 6, it: 7};

/** Return localized copy and replace only explicitly supplied interpolation values. */
export function makingText(locale: Locale, key: MakingKey, values?: Record<string, string | number>): string {
  const template = text[key][localeIndex[locale]];
  if (!values) return template;
  return Object.entries(values).reduce((result, [name, value]) => result.replaceAll(`{${name}}`, String(value)), template);
}
